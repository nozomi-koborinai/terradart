// bump_new_factories.dart — turns the types a weekly schema bump found
// upstream into factories, so a new type never has to wait for a human.
//
// Usage (from repo root; --diff is tool/schema_resource_diff.dart output):
//   dart tool/bump_new_factories.dart scaffold --lane=google \
//     --diff=/tmp/schema_diff.json --out=/tmp/scaffold.json
//   # ... terradart wrap (tool/wrap_lanes.dart --gate regen) ...
//   dart tool/bump_new_factories.dart record --lane=google \
//     --diff=/tmp/schema_diff.json --detected-at=2026-10-04 \
//     --provider-version=7.47.0 --out=/tmp/new_factories.json
//
// scaffold writes a default override for every added type, the way the
// lane's `bump.scaffold` says: `wrap-init` runs tool/batch_wrap_init.dart
// for the added resources (with --fill-param-order, so the override passes
// the universal invariants unedited); `lane` runs scaffold_lane_overrides.dart, which
// fills every schema type that has no override yet. Existing overrides are
// never touched. A lane with Magic Modules YAML (`mm: true`) first gives
// each added resource its tool/mm_yaml_sources.yaml row, fetching the MM
// fixture when a guessed mmv1 path resolves ([guessMmUpstreams]). A new
// override whose barrel the lane's barrels manifest lacks gets a placeholder
// entry there ([addMissingBarrels]).
// --out receives `{exit, log_excerpt}`.
//
// record runs after the regenerate. Every added type the lane's catalog now
// lists is a new factory: it gets a tool/curation_backlog.yaml entry with a
// note asking for API polish and — unless the lane's `bump.exampleGenerator`
// covers every factory — a `ClassName: awaiting-example: ...` line in
// tool/example_debt.yaml (tool/example_synth_gates.dart requires the
// backlog entry). `--example-generator-ok=false` (the generator failed and
// the example was reverted) writes the debt lines anyway. --out receives `{factories: [{tf_type, class_name,
// kind}]}` for the drift report.
//
// exit: 0 success; 1 scaffolding failed; 64 usage error.
// ignore_for_file: avoid_print

