final _mmUpstream = RegExp(r'^mmv1/products/([^/]+)/([^/]+)\.yaml$');

String _snake(String camel) => camel
    .replaceAllMapped(
      RegExp(r'(?<=[a-z0-9])[A-Z]|(?<=[A-Z])[A-Z](?=[a-z])'),
      (m) => '_${m[0]}',
    )
    .toLowerCase();

String _camel(String snake) => [
  for (final w in snake.split('_'))
    if (w.isNotEmpty) w[0].toUpperCase() + w.substring(1),
].join();

@visibleForTesting
List<String> guessMmUpstreams(String type, String mmSources) {
  final files = (loadYaml(mmSources) as YamlMap)['files'] as YamlMap;
  final products = <String, Map<String, int>>{};
  for (final MapEntry(:key, :value) in files.entries) {
    final upstream = (value as YamlMap)['upstream'];
    final m = upstream is String ? _mmUpstream.firstMatch(upstream) : null;
    if (m == null) continue;
    final resource = _snake(m[2]!);
    final row = '$key';
    if (!row.endsWith('_$resource')) continue;
    final prefix = row.substring(0, row.length - resource.length);
    (products[prefix] ??= {}).update(m[1]!, (n) => n + 1, ifAbsent: () => 1);
  }
  final prefixes = [
    for (final prefix in products.keys)
      if (type.startsWith(prefix) && type.length > prefix.length) prefix,
  ]..sort((a, b) => b.length.compareTo(a.length));
  return [
    for (final prefix in prefixes.take(2))
      for (final product
          in (products[prefix]!.entries.toList()
                ..sort((a, b) => b.value.compareTo(a.value)))
              .take(2))
        'mmv1/products/${product.key}/'
            '${_camel(type.substring(prefix.length))}.yaml',
  ];
}

@visibleForTesting
String addMmSourceRows(String mmSources, Map<String, String?> upstreams) {
  final listed = ((loadYaml(mmSources) as YamlMap)['files'] as YamlMap).keys;
  final rows = StringBuffer();
  for (final MapEntry(key: type, value: upstream) in upstreams.entries) {
    if (listed.contains(type)) continue;
    rows
      ..writeln('  $type:')
      ..writeln(
        upstream == null
            ? '    upstream: null  # schema bump: no mmv1 YAML at the guessed '
                  'paths or in the provider Go header; probe upstream by hand'
            : '    upstream: $upstream',
      );
  }
  if (rows.isEmpty) return mmSources;
  final at = mmSources.indexOf(RegExp(r'^  data_', multiLine: true));
  if (at < 0) return '${mmSources.trimRight()}\n$rows';
  return mmSources.replaceRange(at, at, '$rows');
}

@visibleForTesting
String addMmDataSourceRows(String mmSources, List<String> dataSources) {
  final listed = ((loadYaml(mmSources) as YamlMap)['files'] as YamlMap).keys;
  final lines = mmSources.trimRight().split('\n');
  final key = RegExp(r'^  (data_[a-z0-9_]+):$');
  for (final stem in [
    for (final type in dataSources)
      if (!listed.contains('data_$type')) 'data_$type',
  ]..sort()) {
    var at = lines.length;
    for (var i = 0; i < lines.length; i++) {
      final m = key.firstMatch(lines[i]);
      if (m != null && m[1]!.compareTo(stem) > 0) {
        at = i;
        break;
      }
    }
    lines.insertAll(at, [
      '  $stem:',
      '    upstream: null  # data source; no mmv1 YAML (schema bump)',
    ]);
  }
  return '${lines.join('\n')}\n';
}

@visibleForTesting
List<String> scaffoldDataSourceOverrides(
  List<String> dataSources, {
  required String schema,
  required String overridesRoot,
}) {
  final defs = const SchemaJsonParser().parseString(schema).dataSources;
  final written = <String>[];
  for (final type in dataSources) {
    final file = File(p.join(overridesRoot, 'data_$type.yaml'));
    if (file.existsSync()) continue;
    final def =
        defs[type] ??
        (throw StateError('$type is not a data source of the lane schema'));
    file.writeAsStringSync(dataSourceOverrideYaml(dataSourceParamOrder(def)));
    written.add(type);
  }
  return written;
}

typedef MmFetch = Future<String?> Function(String upstreamPath);

MmFetch mmFetchAt(Manifest manifest, String ref) => (upstreamPath) async {
  try {
    final r = await http.get(
      Uri.parse(manifest.urlFor(upstreamPath, ref: ref)),
    );
    return r.statusCode == 200 ? r.body : null;
  } on Exception {
    return null;
  }
};

typedef GoHeaderLookup = Future<String?> Function(String type);

@visibleForTesting
Future<Map<String, String?>> resolveMmUpstreams(
  List<String> resources, {
  required String mmSources,
  required String mmDir,
  required MmFetch fetch,
  GoHeaderLookup? goHeader,
}) async {
  final out = <String, String?>{};
  for (final type in resources) {
    out[type] = null;
    Future<bool> take(String path) async {
      final body = await fetch(path);
      if (body == null) return false;
      File(p.join(mmDir, '$type.yaml'))
        ..createSync(recursive: true)
        ..writeAsStringSync(body);
      out[type] = path;
      return true;
    }

    for (final path in guessMmUpstreams(type, mmSources)) {
      if (await take(path)) break;
    }
    if (out[type] != null || goHeader == null) continue;
    final header = mmPathFromGoHeader(await goHeader(type) ?? '');
    if (header != null) await take(header);
  }
  return out;
}

GoHeaderLookup? googleGoHeader(WrapLane lane) {
  final repo = lane.hintsRepo;
  if (lane.source != 'hashicorp/google' || repo == null) return null;
  final version = File(
    p.join(lane.schemaDir, 'provider_version.txt'),
  ).readAsStringSync().trim();
  const servicesDir = 'google/services';
  Map<String, String>? goFiles;
  return (type) async {
    try {
      goFiles ??= resourceGoFiles(
        await githubTreePaths(repo, 'v$version'),
        servicesDir,
      );
      final path = goFiles![resourceGoFileName(type)];
      if (path == null) return null;
      return await githubRaw(repo, 'v$version', path);
    } on Exception {
      return null;
    }
  };
}

