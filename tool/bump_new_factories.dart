Never _usage() {
  stderr.writeln(
    'usage: dart tool/bump_new_factories.dart scaffold --lane=<name> '
    '--diff=<json> --out=<json>\n'
    '       dart tool/bump_new_factories.dart record --lane=<name> '
    '--diff=<json> --detected-at=<date> --provider-version=<v> --out=<json> '
    '[--coverage=<coverage_stack.json>]',
  );
  exit(64);
}

Future<void> main(List<String> args) async {
  final command = args.isEmpty ? null : args.first;
  final flags = _flags(args);
  final laneName = flags['lane'];
  final diffPath = flags['diff'];
  final outPath = flags['out'];
  if (laneName == null || diffPath == null || outPath == null) _usage();
  final lane = parseBumpLanes(
    File(providersPath).readAsStringSync(),
  ).where((l) => l.lane.name == laneName).firstOrNull;
  if (lane == null) {
    stderr.writeln('bump_new_factories: no bump lane "$laneName"');
    exit(64);
  }
  final diff =
      jsonDecode(File(diffPath).readAsStringSync()) as Map<String, dynamic>;
  switch (command) {
    case 'scaffold':
      exit(await _scaffold(lane, diff, outPath));
    case 'record':
      final detectedAt = flags['detected-at'];
      final version = flags['provider-version'];
      if (detectedAt == null || version == null) _usage();
      final coverage = switch (flags['coverage']) {
        final path? when File(path).existsSync() => decodeVerdict(
          jsonDecode(File(path).readAsStringSync()),
        ),
        _ => null,
      };
      _record(lane, diff, outPath, detectedAt, version, coverage: coverage);
    default:
      _usage();
  }
}

Future<int> _scaffold(
  BumpLane lane,
  Map<String, dynamic> diff,
  String outPath,
) async {
  List<String> added(String key) =>
      ((diff[key] as List?) ?? const []).cast<String>();
  final resources = added('added_resources');
  final dataSources = lane.dataSources
      ? added('added_data_sources')
      : <String>[];
  final ProcessResult? result;
  if (resources.isEmpty && dataSources.isEmpty) {
    result = null;
  } else if (lane.scaffold == 'wrap-init') {
    result = await _wrapInit(lane, resources, dataSources);
  } else {
    result = await Process.run(Platform.resolvedExecutable, [
      'run',
      'tool/scaffold_lane_overrides.dart',
      '--provider',
      lane.lane.source,
    ], workingDirectory: codegenDir);
  }
  final code = result?.exitCode ?? 0;
  var log = result == null
      ? 'no new types'
      : '${result.stdout}${result.stderr}';
  if (result != null && code == 0) {
    final manifest = File(lane.lane.barrelsManifest);
    final text = manifest.readAsStringSync();
    final next = addMissingBarrels(
      text,
      overrideBarrels(lane.lane.overridesRoot),
    );
    if (next != text) {
      manifest.writeAsStringSync(next);
      log += '\nadded barrel entries to ${lane.lane.barrelsManifest}';
    }
  }
  print(log);
  File(outPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(
      jsonEncode({
        'exit': code,
        'log_excerpt': code == 0
            ? ''
            : log.length > 2000
            ? log.substring(log.length - 2000)
            : log,
      }),
    );
  return code == 0 ? 0 : 1;
}

Future<ProcessResult> _wrapInit(
  BumpLane lane,
  List<String> resources,
  List<String> dataSources,
) async {
  final sources = File(mmSourcesPath);
  var out = '';
  if (resources.isNotEmpty) {
    if (lane.mm) {
      final manifest = parseManifest(sources.readAsStringSync());
      final upstreams = await resolveMmUpstreams(
        resources,
        mmSources: sources.readAsStringSync(),
        mmDir: p.join(lane.lane.schemaDir, 'mm'),
        fetch: mmFetchAt(manifest, recordedUpstreamRef(manifest)),
        goHeader: googleGoHeader(lane.lane),
      );
      print('MM upstreams: $upstreams');
      sources.writeAsStringSync(
        addMmSourceRows(sources.readAsStringSync(), upstreams),
      );
    }
    final result = await Process.run(Platform.resolvedExecutable, [
      'tool/batch_wrap_init.dart',
      '--resources=${resources.join(',')}',
      '--source=${lane.lane.schemaDir}',
      '--output=${lane.lane.overridesRoot}',
      '--fill-param-order',
    ]);
    if (result.exitCode != 0 || dataSources.isEmpty) return result;
    out = '${result.stdout}';
  }
  try {
    final written = scaffoldDataSourceOverrides(
      dataSources,
      schema: File(
        p.join(lane.lane.schemaDir, 'schema.json'),
      ).readAsStringSync(),
      overridesRoot: lane.lane.overridesRoot,
    );
    if (lane.mm) {
      sources.writeAsStringSync(
        addMmDataSourceRows(sources.readAsStringSync(), dataSources),
      );
    }
    out += 'data-source overrides: ${written.join(', ')}\n';
    return ProcessResult(pid, 0, out, '');
  } on Object catch (e) {
    return ProcessResult(pid, 1, out, '$e\n');
  }
}

void _record(
  BumpLane lane,
  Map<String, dynamic> diff,
  String outPath,
  String detectedAt,
  String version, {
  required CoverageVerdict? coverage,
}) {
  final catalog = readCatalog(
    File(
      p.join(lane.lane.outputPackage, 'lib', 'src', '_catalog.g.dart'),
    ).readAsStringSync(),
  );
  final factories = newFactories(diff, catalog);
  final uncovered = awaitingExample(factories, lane.exampleCovers, coverage);
  final existing = leftExisting(coverage, factories);
  final backlog = File(curationBacklogPath);
  for (final (types, note) in [
    (factories, generatedFactoryNote),
    (
      [
        for (final e in existing)
          (tfType: e.tfType, className: e.className, kind: e.kind.name),
      ],
      leftCoverageNote(lane.lane.name),
    ),
  ]) {
    if (types.isEmpty) continue;
    final text = backlog.readAsStringSync();
    backlog.writeAsStringSync(
      formatBacklogYaml(
        header: readBacklogHeader(text),
        entries: appendCurationEntries(
          existing: readBacklogEntries(text),
          resources: [
            for (final f in types)
              if (f.kind == 'resource') f.tfType,
          ],
          dataSources: [
            for (final f in types)
              if (f.kind == 'dataSource') f.tfType,
          ],
          detectedAt: detectedAt,
          providerVersion: version,
          note: note,
        ),
      ),
    );
  }
  if (uncovered.isNotEmpty || existing.isNotEmpty) {
    final debt = File(exampleDebtPath);
    debt.writeAsStringSync(
      appendAwaitingExampleDebt(
        debt.readAsStringSync(),
        factories: uncovered,
        leftOut: coverage is CoverageGreen ? coverage.excluded : const [],
        source: lane.lane.source,
        providerVersion: version,
        detectedAt: detectedAt,
      ),
    );
  }
  print(
    'bump_new_factories: ${factories.length} new factories'
    '${factories.isEmpty ? '' : ': ${factories.map((f) => f.className).join(', ')}'}'
    '${existing.isEmpty ? '' : '; ${existing.length} existing left the '
              'coverage stack: ${existing.map((e) => e.className).join(', ')}'}',
  );
  File(outPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(
      jsonEncode({
        'example_generator': coverage is CoverageGreen
            ? lane.exampleGenerator
            : null,
        'factories': [
          for (final f in factories)
            {
              'tf_type': f.tfType,
              'class_name': f.className,
              'kind': f.kind,
              'example_covered': !uncovered.contains(f),
            },
        ],
      }),
    );
}
