@visibleForTesting
String addMissingBarrels(String manifest, Set<String> barrels) {
  final existing = ((loadYaml(manifest) as YamlMap)['barrels'] as YamlMap).keys
      .toSet();
  final missing = barrels.difference(existing).toList()..sort();
  if (missing.isEmpty) return manifest;
  final lines = manifest.trimRight().split('\n');
  final start = lines.indexOf('barrels:');
  final key = RegExp(r'^  ([a-z0-9_]+):$');
  for (final barrel in missing) {
    var at = lines.length;
    for (var i = start + 1; i < lines.length; i++) {
      final m = key.firstMatch(lines[i]);
      if (m != null && m[1]!.compareTo(barrel) > 0) {
        at = i;
        break;
      }
    }
    lines.insertAll(at, [
      '  $barrel:',
      '    doc: |-',
      '      /// `$barrel` factories, added by the weekly schema bump.',
    ]);
  }
  return '${lines.join('\n')}\n';
}

typedef CatalogFactory = ({String tfType, String className, String kind});

List<CatalogFactory> readCatalog(String source) => [
  for (final m in RegExp(
    r"tfType:\s*'([^']+)'[\s\S]*?className:\s*'([^']+)'[\s\S]*?"
    r'kind:\s*CatalogKind\.(\w+)',
  ).allMatches(source))
    (tfType: m[1]!, className: m[2]!, kind: m[3]!),
];

@visibleForTesting
List<CatalogFactory> newFactories(
  Map<String, dynamic> diff,
  List<CatalogFactory> catalog,
) {
  final byKey = {for (final f in catalog) '${f.kind}:${f.tfType}': f};
  return [
    for (final (kind, key) in [
      ('resource', 'added_resources'),
      ('dataSource', 'added_data_sources'),
    ])
      for (final type in ((diff[key] as List?) ?? const []).cast<String>())
        ?byKey['$kind:$type'],
  ];
}

@visibleForTesting
List<CatalogFactory> awaitingExample(
  List<CatalogFactory> factories,
  Set<String> coveredKinds,
  CoverageVerdict? coverage,
) {
  if (coverage is! CoverageGreen) return factories;
  final leftOut = {for (final e in coverage.excluded) e.typeKey};
  return [
    for (final f in factories)
      if (!coveredKinds.contains(f.kind) ||
          leftOut.contains('${f.kind}:${f.tfType}'))
        f,
  ];
}

@visibleForTesting
List<ExcludedFactory> leftExisting(
  CoverageVerdict? coverage,
  List<CatalogFactory> factories,
) {
  if (coverage is! CoverageGreen) return const [];
  final added = {for (final f in factories) '${f.kind}:${f.tfType}'};
  return [
    for (final e in coverage.excluded)
      if (!added.contains(e.typeKey)) e,
  ];
}

@visibleForTesting
String appendAwaitingExampleDebt(
  String debtYaml, {
  required List<CatalogFactory> factories,
  List<ExcludedFactory> leftOut = const [],
  required String source,
  required String providerVersion,
  required String detectedAt,
}) {
  final listed = {
    for (final line in debtYaml.split('\n'))
      if (!line.trimLeft().startsWith('#') && line.contains(':'))
        line.substring(0, line.indexOf(':')).trim(),
  };
  final why = {for (final e in leftOut) e.typeKey: _leftOutBecause(e.cause)};
  final at = '$source $providerVersion (schema bump $detectedAt)';
  final lines = <String>[];
  for (final f in factories) {
    final because = why.remove('${f.kind}:${f.tfType}');
    if (listed.add(f.className)) {
      lines.add(
        '${f.className}: $awaitingExampleToken ${f.tfType} '
        '${f.kind == 'dataSource' ? '(data source) ' : ''}added in $at'
        '${because == null ? '' : '; the coverage stack left it out: $because'}',
      );
    }
  }
  for (final e in leftOut) {
    final because = why[e.typeKey];
    if (because != null && listed.add(e.className)) {
      lines.add(
        '${e.className}: $awaitingExampleToken ${e.tfType} '
        '${e.kind == FactoryKind.dataSource ? '(data source) ' : ''}'
        'left the coverage stack in $at: $because',
      );
    }
  }
  if (lines.isEmpty) return debtYaml;
  final b = StringBuffer(debtYaml.trimRight());
  if (!debtYaml.contains(_debtSectionHeader)) {
    b
      ..writeln()
      ..writeln()
      ..write(_debtSectionHeader);
  }
  b.writeln();
  lines.forEach(b.writeln);
  return b.toString();
}

String _leftOutBecause(ExclusionCause cause) {
  String oneLine(String s) => s.trim().replaceAll(RegExp(r'\s+'), ' ');
  return switch (cause) {
    ProviderRejected(:final at, :final rejected?, :final detail) =>
      '$at rejected ${rejected is String ? rejected : jsonEncode(rejected)}: '
          '${oneLine(detail)}',
    ProviderRejected(:final at, :final detail) => '$at: ${oneLine(detail)}',
    GeneratorCannotPlace(:final reason) => oneLine(reason),
  };
}

